"""Build the on-demand terrain pyramid from NASA's eight August 2004 Blue Marble 500 m JPEGs.

Usage: python3 tools/build_terrain.py /path/to/downloads
Inputs are A1.jpg through D2.jpg, each 21600 x 21600, from the URLs recorded
in public/textures/terrain-tiles/source.json, and overview.jpg (21600 x 10800)
from the global-image URL in terrain-source.txt. Requires Pillow, not at runtime.
"""
from pathlib import Path
from PIL import Image
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sys.argv[1])
OUT = ROOT / 'public/textures/terrain-tiles'
SIZE, BORDER, TILE = 21600, 32, 1350
# The explicitly verified NASA images are larger than Pillow's generic limit.
Image.MAX_IMAGE_PIXELS = None
edges, hashes = {}, {}

def read(name):
    image = Image.open(SOURCE / (name + '.jpg'))
    if image.size != (SIZE, SIZE):
        raise ValueError(f'Unexpected NASA image size for {name}: {image.size}')
    return image.convert('RGB')

for row in range(2):
    for col in range(4):
        name = f'{chr(65+col)}{row+1}'
        image = read(name)
        edges[col, row] = {
            'n': image.crop((0, 0, SIZE, BORDER)),
            's': image.crop((0, SIZE-BORDER, SIZE, SIZE)),
            'w': image.crop((0, 0, BORDER, SIZE)),
            'e': image.crop((SIZE-BORDER, 0, SIZE, SIZE)),
            'nw': image.crop((0, 0, BORDER, BORDER)),
            'ne': image.crop((SIZE-BORDER, 0, SIZE, BORDER)),
            'sw': image.crop((0, SIZE-BORDER, BORDER, SIZE)),
            'se': image.crop((SIZE-BORDER, SIZE-BORDER, SIZE, SIZE)),
        }
        hashes[name] = hashlib.sha256((SOURCE / (name + '.jpg')).read_bytes()).hexdigest()
        image.close()
        print('Read source', name, flush=True)

levels = [{'columns': 8*2**i, 'rows': 4*2**i} for i in range(4)]
OUT.mkdir(parents=True, exist_ok=True)
for level in range(4):
    (OUT / str(level)).mkdir(exist_ok=True)

for row in range(2):
    for col in range(4):
        name = f'{chr(65+col)}{row+1}'
        image = read(name)
        padded = Image.new('RGB', (SIZE+2*BORDER, SIZE+2*BORDER))
        padded.paste(image, (BORDER, BORDER))
        image.close()
        own = edges[col, row]
        west, east = edges[(col-1)%4, row], edges[(col+1)%4, row]
        padded.paste(west['e'], (0, BORDER))
        padded.paste(east['w'], (SIZE+BORDER, BORDER))
        for side, other_row, y, edge, corner_l, corner_r in [
            ('n', row-1, 0, 's', 'se', 'sw'),
            ('s', row+1, SIZE+BORDER, 'n', 'ne', 'nw')
        ]:
            if 0 <= other_row < 2:
                padded.paste(edges[col, other_row][edge], (BORDER, y))
                padded.paste(edges[(col-1)%4, other_row][corner_l], (0, y))
                padded.paste(edges[(col+1)%4, other_row][corner_r], (SIZE+BORDER, y))
            else:
                # Longitude wraps, latitude clamps at the poles.
                yy = 0 if side == 'n' else BORDER-1
                for source, x in [(west, 0), (own, BORDER), (east, SIZE+BORDER)]:
                    strip = source[side].crop((0, yy, SIZE, yy+1))
                    if x == 0: strip = strip.crop((SIZE-BORDER, 0, SIZE, 1))
                    elif x > BORDER: strip = strip.crop((0, 0, BORDER, 1))
                    padded.paste(strip.resize((strip.width, BORDER)), (x, y))
        for level, factor in enumerate([8, 4, 2, 1]):
            scaled = padded if factor == 1 else padded.resize(
                (padded.width//factor, padded.height//factor), Image.Resampling.LANCZOS)
            count, offset = SIZE//factor//TILE, BORDER//factor
            for ty in range(count):
                for tx in range(count):
                    x, y = offset+tx*TILE, offset+ty*TILE
                    tile = scaled.crop((x-1, y-1, x+TILE+1, y+TILE+1))
                    gx, gy = col*count+tx, row*count+ty
                    tile.save(OUT / str(level) / f'{gx}-{gy}.jpg', quality=90, subsampling=0, optimize=True)
                    tile.close()
            if scaled is not padded: scaled.close()
        padded.close()
        print('Built region', name, flush=True)

layout = {'tileSize': TILE, 'gutter': 1, 'levels': levels}
(ROOT / 'src/data/terrainTiles.js').write_text(
    '// Generated by tools/build_terrain.py from NASA Blue Marble August 2004, 500 m.\n'
    'export default '+json.dumps(layout, separators=(',', ':'))+';\n')
base = 'https://assets.science.nasa.gov/content/dam/science/esd/eo/images/bmng/bmng-topography-bathymetry/august/'
(OUT / 'source.json').write_text(json.dumps({
    'dataset': 'NASA Blue Marble Next Generation, August 2004, topography and bathymetry, 500 m',
    'map': 'https://science.nasa.gov/earth/earth-observatory/blue-marble-next-generation/base-topography-bathymetry/',
    'globalDimensions': [86400, 43200],
    'processing': 'Geographic crops; 4 km, 2 km and 1 km LANCZOS levels; native 500 m level. RGB JPEG quality 90, no chroma subsampling. Neighboring-pixel gutters. No upscaling or artificial sharpening.',
    'sources': {name: {'url': base+f'world.topo.bathy.200408.3x21600x21600.{name}.jpg', 'sha256': sha} for name, sha in hashes.items()}
}, indent=2)+'\n')
overview = Image.open(SOURCE / 'overview.jpg')
for width, name in [(8192, 'earth-day.jpg'), (4096, 'earth-day-mobile.jpg')]:
    overview.resize((width, width//2), Image.Resampling.LANCZOS).save(ROOT / 'public/textures' / name, quality=90, subsampling=0, optimize=True)
overview.close()
files = list(OUT.glob('*/*.jpg'))
print('Finished:', len(files), 'tiles,', sum(p.stat().st_size for p in files), 'bytes', flush=True)
